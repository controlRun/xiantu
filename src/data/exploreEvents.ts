/** 按境界与地区过滤事件池：地区缺省时仅按境界（兼容旧调用） */
export const getExploreEventsForRealmOrder = (realmOrder: number, area?: string) =>
  exploreEvents.filter(
    (event) =>
      realmOrder >= event.minRealmOrder &&
      (!event.areas || (area !== undefined && event.areas.includes(area))),
  );
